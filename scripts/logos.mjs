// Writes src/lib/logos.ts: only the Simple Icons (CC0) we use, and only their path and colour.
// The full objects also carry an SVG copy of the path and licence metadata, ~3x the bytes.
// Run after changing the list: npm run logos
import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

const USED = ['Arstechnica', 'Arxiv', 'Bluesky', 'Cloudflare', 'Cncf', 'Datadog', 'Deepmind', 'Devdotto', 'Duckdb', 'Flydotio', 'Github', 'Go', 'Google', 'Grafana', 'Huggingface', 'Infoq', 'Lemmy', 'Lobsters', 'Mastodon', 'Meta', 'Mozilla', 'Netflix', 'Nvidia', 'Opentelemetry', 'Planetscale', 'Postgresql', 'Prometheus', 'Rss', 'Rust', 'Stripe', 'Tailscale', 'Theregister', 'Ycombinator']

const lines = USED.map((name) => {
  const icon = si[`si${name}`]
  if (!icon) throw new Error(`No Simple Icon named si${name}`)
  return `export const si${name}: Logo = { title: ${JSON.stringify(icon.title)}, hex: '${icon.hex}', path: '${icon.path}' }`
})
writeFileSync(
  new URL('../src/lib/logos.ts', import.meta.url),
  `// Generated by scripts/logos.mjs from simple-icons (CC0-1.0). Do not edit by hand.\nexport interface Logo {\n  title: string\n  hex: string\n  path: string\n}\n\n${lines.join('\n')}\n`,
)
console.log(`wrote ${USED.length} logos`)
