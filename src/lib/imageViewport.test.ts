import { describe, expect, it } from 'vitest'
import { createImageViewport } from './imageViewport'

const viewport = () => createImageViewport({ width: 300, height: 500, imageWidth: 300, imageHeight: 300 })
describe('image gestures', () => {
  it('zooms around the pinch midpoint and pans within the image', () => {
    const v = viewport()
    v.down(1, { x: 100, y: 250 })
    v.down(2, { x: 200, y: 250 })
    v.move(1, { x: 50, y: 250 })
    v.move(2, { x: 250, y: 250 })
    expect(v.view().scale).toBe(2)
    expect(v.view().x).toBe(0)
    expect(v.up(2)).toBe(0)
    v.move(1, { x: 200, y: 400 })
    expect(v.view()).toEqual({ scale: 2, x: 150, y: 50 })
    expect(v.up(1)).toBe(0)
  })
  it('only changes slides after a deliberate unzoomed single-finger swipe', () => {
    const v = viewport()
    v.down(1, { x: 250, y: 250 })
    v.move(1, { x: 50, y: 250 })
    expect(v.up(1)).toBe(1)
    v.down(1, { x: 50, y: 250 })
    v.move(1, { x: 250, y: 250 })
    expect(v.up(1)).toBe(-1)
    v.down(1, { x: 150, y: 250 })
    v.move(1, { x: 120, y: 350 })
    expect(v.up(1)).toBe(0)
    v.down(1, { x: 250, y: 250 })
    v.move(1, { x: 50, y: 250 })
    v.cancel()
    expect(v.up(1)).toBe(0)
  })
  it('never treats the remainder of a pinch as a slide swipe, even when zoom returns to fit', () => {
    const v = viewport()
    v.down(1, { x: 250, y: 250 })
    v.down(2, { x: 150, y: 250 })
    v.move(1, { x: 200, y: 250 })
    v.up(2)
    v.move(1, { x: 20, y: 250 })
    expect(v.view().scale).toBe(1)
    expect(v.up(1)).toBe(0)
  })
  it('bounds zoom, resets position, and clamps after a resize', () => {
    const v = viewport()
    v.zoom(20)
    expect(v.view().scale).toBe(4)
    v.down(1, { x: 100, y: 100 })
    v.move(1, { x: 900, y: 900 })
    v.up(1)
    v.resize({ width: 1000, height: 1000, imageWidth: 200, imageHeight: 200 })
    expect(v.view()).toEqual({ scale: 4, x: 0, y: 0 })
    v.zoom(0)
    expect(v.view()).toEqual({ scale: 1, x: 0, y: 0 })
  })
})
